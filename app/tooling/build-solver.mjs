// Bundles the interior design solver (themes + furnishing, pure TypeScript) for Node, so the
// engine's interior-designer agent validates proposals with exactly the code the editor uses.
//   node tooling/build-solver.mjs            → ../engine/constructos_engine/interior/solver.mjs
//   node tooling/build-solver.mjs --check    → exit 1 when the committed bundle is stale
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const outfile = fileURLToPath(new URL('../../engine/constructos_engine/interior/solver.mjs', import.meta.url));
const stubs = { '$app/paths': 'export const base = "";', 'virtual:catalog-assets': 'export default {};' };

const result = await build({
  entryPoints: [`${root}src/lib/constructos/designCli.ts`],
  bundle: true, platform: 'node', format: 'esm', target: 'node18', write: false, logLevel: 'warning',
  alias: { $lib: `${root}src/lib` }, legalComments: 'none',
  banner: { js: '// Generated by app/tooling/build-solver.mjs from app/src/lib/constructos — do not edit.' },
  plugins: [{
    name: 'stubs',
    setup(b) {
      b.onResolve({ filter: /^(\$app\/paths|virtual:catalog-assets)$/ }, a => ({ path: a.path, namespace: 'stub' }));
      b.onLoad({ filter: /.*/, namespace: 'stub' }, a => ({ contents: stubs[a.path], loader: 'js' }));
    },
  }],
});
const code = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(outfile, 'utf8'); } catch { /* missing */ }
  if (current !== code) { console.error('solver.mjs is stale: run node tooling/build-solver.mjs'); process.exit(1); }
  console.log('solver.mjs is up to date');
} else {
  const { writeFileSync } = await import('node:fs');
  writeFileSync(outfile, code);
  console.log(`wrote ${outfile} (${(code.length / 1024).toFixed(0)} KiB)`);
}
