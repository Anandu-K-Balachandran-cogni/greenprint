<script lang="ts">
  import { page } from '$app/state';
  import { onMount } from 'svelte';
  import { agents, diagrams, downloadExport, planExport, EngineError, type DiagramSummary, type ExportFormat } from '$lib/constructos/engine';
  import { CIRCUIT_STYLE, renderDiagramSvg, type Diagram } from '$lib/constructos/diagramSvg';
  import CostPanel from '$lib/constructos/CostPanel.svelte';
  import GreenPanel from '$lib/constructos/GreenPanel.svelte';
  import { routingSource, type RoutingSource } from '$lib/constructos/routingSource';
  import type { CompiledProject } from '$lib/constructos/compiler';
  import { localStore } from '$lib/services/datastore';

  type Kind = 'electrical' | 'plumbing';
  const KINDS: Kind[] = ['electrical', 'plumbing'];
  const TITLE: Record<Kind, string> = { electrical: 'Electrical 2D', plumbing: 'Plumbing 2D' };

  const editorId = $derived(decodeURIComponent(page.params.editorId ?? ''));
  let project = $state<CompiledProject | null>(null);
  let source = $state<RoutingSource | null>(null);
  let history = $state<Record<Kind, DiagramSummary[]>>({ electrical: [], plumbing: [] });
  let shown = $state<Record<Kind, Diagram | null>>({ electrical: null, plumbing: null });
  let loadError = $state<string | null>(null);
  let actionError = $state<string | null>(null);
  let busy = $state(false);
  let floor = $state(0);
  let zoom = $state(1);
  let tab = $state<Kind>('electrical');
  let view = $state<'diagrams' | 'cost' | 'green'>('diagrams');
  let estimateId = $state<string | null>(null);
  let greenId = $state<string | null>(null);
  const savedSource = async () => (source = await routingSource(await localStore.load(editorId) as CompiledProject));
  // electrical settings
  let dbRoom = $state('');
  let preferences = $state('');
  // plumbing settings
  let entryRoom = $state('');
  let exitRoom = $state('');

  const engineProjectId = $derived(project?.constructos?.engineProjectId ?? '');
  const diagram = $derived(shown[tab]);
  const current = $derived(!!diagram && !!source && diagram.source_hash === source.source_hash);
  const svg = $derived(diagram ? renderDiagramSvg(diagram, floor) : '');
  const groundRooms = $derived(source?.rooms.filter(r => r.floor === 0 && !r.outdoor && r.type !== 'stair') ?? []);
  const networks = $derived(diagram?.network_metrics ? Object.entries(diagram.network_metrics) : diagram ? [['wiring', diagram.metrics] as const] : []);

  onMount(async () => {
    try {
      const p = await localStore.load(editorId) as CompiledProject | null;
      if (!p) { loadError = 'This project is not in this browser’s library.'; return; }
      if (!p.constructos) { loadError = 'Service diagrams are available for buildings generated by Greenprint.'; return; }
      project = p;
      source = await routingSource(p);
      const all = await diagrams.list(p.constructos.engineProjectId, editorId);
      for (const k of KINDS) {
        history[k] = all.filter(d => d.kind === k);
        const latest = history[k].at(-1);
        if (latest) shown[k] = await diagrams.get(p.constructos.engineProjectId, latest.id);
      }
    } catch (e) {
      loadError = e instanceof EngineError ? e.message : 'Could not load the saved plan or its diagrams.';
    }
  });

  async function generate() {
    if (!project) return;
    busy = true; actionError = null;
    const kind = tab;
    try {
      // Always route the plan exactly as it is saved now.
      source = await routingSource(await localStore.load(editorId) as CompiledProject);
      const d = kind === 'electrical'
        ? await diagrams.electrical(engineProjectId, { source, db_room: dbRoom || null, preferences: preferences.trim() || null })
        : await diagrams.plumbing(engineProjectId, { source, entry_room: entryRoom || null, exit_room: exitRoom || null });
      shown[kind] = d;
      history[kind] = [...history[kind], { id: d.id, kind, created_at: d.created_at, editor_project_id: editorId, source_hash: d.source_hash,
        status: d.status, improvement_pct: d.metrics.improvement_pct, endpoints_connected: d.metrics.endpoints_connected, endpoints_total: d.metrics.endpoints_total }];
    } catch (e) {
      actionError = e instanceof EngineError ? e.message : 'Diagram generation failed; the previous diagram is unchanged.';
    } finally { busy = false; }
  }

  async function show(id: string) { shown[tab] = await diagrams.get(engineProjectId, id); }

  // Greenprint agents (Neuro-SAN): the front agent brings in the architect and the engineers. The
  // conversation context stays in this page; every result is stored with the project, so a new
  // conversation picks up from the project's state.
  type ChatLine = { role: 'user' | 'agent'; text: string; tools?: string[]; seconds?: number; revision?: string | null };
  let chatLog = $state<ChatLine[]>([]);
  let chatInput = $state('');
  let chatContext = $state<Record<string, unknown> | null>(null);
  let asking = $state(false);
  const toolName = (t: string) => ({ '/architect': 'architect', '/electrical_engineer': 'electrical engineer',
    '/plumbing_engineer': 'plumbing engineer', '/cost_estimator': 'cost estimator', '/sustainability_advisor': 'sustainability advisor',
    '/interior_designer': 'interior designer', project_status: 'project status' } as Record<string, string>)[t] ?? t.replace(/^\//, '').replace(/_/g, ' ');
  // "Greenprint, with the architect and the cost estimator": who helped answer, in plain words.
  const helpers = (tools: string[] = []) => {
    const names = [...new Set(tools.map(toolName))].map(n => n === 'project status' ? 'a look at the project status' : `the ${n}`);
    return names.length ? `Greenprint, with ${names.length > 1 ? `${names.slice(0, -1).join(', ')} and ${names.at(-1)}` : names[0]}` : 'Greenprint';
  };
  async function ask() {
    const message = chatInput.trim();
    if (!message || !project || asking) return;
    chatLog = [...chatLog, { role: 'user', text: message }];
    chatInput = ''; asking = true; actionError = null;
    try {
      const saved = await localStore.load(editorId) as CompiledProject;
      source = await routingSource(saved);
      const link = project.constructos;
      const layout = link?.layoutRunId ? { run_id: link.layoutRunId, candidate: link.candidate ?? 0 } : null;
      const reply = await agents.chat(engineProjectId, 'constructos', { message, source, layout, floors: saved.floors, chat_context: chatContext });
      chatContext = reply.chat_context;
      chatLog = [...chatLog, { role: 'agent', text: reply.answer, tools: reply.tools_called, seconds: reply.seconds, revision: reply.revision_run_id }];
      const changed = Object.entries(reply.diagrams) as [Kind, string][];
      if (changed.length) {
        const all = await diagrams.list(engineProjectId, editorId);
        for (const [kind, id] of changed) {
          history[kind] = all.filter(d => d.kind === kind);
          shown[kind] = await diagrams.get(engineProjectId, id);
        }
        if (!changed.some(([kind]) => kind === tab)) tab = changed[0][0];
        view = 'diagrams';
      }
      if (reply.estimate_id) { estimateId = reply.estimate_id; view = 'cost'; }
      if (reply.green_id) { greenId = reply.green_id; view = 'green'; }
    } catch (e) {
      chatLog = [...chatLog, { role: 'agent', text: e instanceof EngineError ? e.message : 'Greenprint is not reachable right now.' }];
    } finally { asking = false; }
  }

  function download() {
    if (!diagram) return;
    const a = document.createElement('a');
    a.href = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' }));
    a.download = `${(project?.name ?? 'building').replace(/[^\w-]+/g, '_')}-${tab}-floor${floor}-${diagram.source_hash.slice(7, 15)}.svg`;
    a.click();
    URL.revokeObjectURL(a.href);
  }

  let exporting = $state<string | null>(null);
  async function exportFile(what: 'diagram' | 'plan', fmt: ExportFormat) {
    if (!source || (what === 'diagram' && !diagram)) return;
    exporting = `${what}-${fmt}`; actionError = null;
    try {
      if (what === 'plan') await planExport(engineProjectId, fmt, source);
      else await downloadExport(diagrams.exportUrl(engineProjectId, diagram!.id, fmt));
    } catch (e) {
      actionError = e instanceof EngineError ? e.message : 'The export failed.';
    } finally { exporting = null; }
  }

  const km = (mm: number) => `${(mm / 1000).toFixed(1)} m`;
  const NETWORK_LABEL: Record<string, string> = { wiring: 'Wiring', supply: 'Cold water supply', drainage: 'Drainage' };
</script>

<svelte:head><title>Greenprint — Service diagrams</title></svelte:head>

<div class="min-h-screen bg-gray-50">
  <header class="bg-gradient-to-r from-slate-800 to-slate-700">
    <div class="max-w-7xl mx-auto px-6 py-5 flex items-center justify-between gap-4">
      <div>
        <a href="/editor?id={encodeURIComponent(editorId)}" class="text-xs text-white/60 hover:text-white">← Back to the editor</a>
        <h1 class="text-2xl font-bold text-white">{project?.name ?? 'Service diagrams'}</h1>
      </div>
      {#if source}
        <div class="text-right space-y-1">
          <div class="flex gap-1 justify-end items-center" role="group" aria-label="Export floor plan">
            <span class="text-xs text-white/70 mr-1">Floor plan:</span>
            {#each ['pdf', 'dxf'] as const as fmt}
              <button type="button" class="px-2 py-0.5 text-xs rounded border border-white/30 text-white hover:bg-white/10 disabled:opacity-50"
                disabled={exporting !== null} onclick={() => exportFile('plan', fmt)}>{exporting === `plan-${fmt}` ? 'Exporting…' : fmt.toUpperCase()}</button>
            {/each}
          </div>
        </div>
      {/if}
    </div>
  </header>

  <main class="max-w-7xl mx-auto px-6 py-6 space-y-5">
    {#if loadError}
      <p role="alert" class="text-sm text-red-700 bg-red-50 border border-red-200 rounded-lg px-3 py-2">{loadError}</p>
    {:else if !source}
      <p role="status" class="text-gray-500">Loading the saved plan…</p>
    {:else}
      <div class="flex gap-2" role="tablist" aria-label="Service">
        {#each KINDS as k}
          <button role="tab" aria-selected={view === 'diagrams' && tab === k} class="px-4 py-2 rounded-lg text-sm font-medium {view === 'diagrams' && tab === k ? 'bg-slate-800 text-white' : 'bg-white border'}"
            onclick={() => { tab = k; view = 'diagrams'; actionError = null; }}>{TITLE[k]}</button>
        {/each}
        <button role="tab" aria-selected={view === 'cost'} class="px-4 py-2 rounded-lg text-sm font-medium {view === 'cost' ? 'bg-slate-800 text-white' : 'bg-white border'}"
          onclick={() => { view = 'cost'; actionError = null; }}>Cost</button>
        <button role="tab" aria-selected={view === 'green'} class="px-4 py-2 rounded-lg text-sm font-medium {view === 'green' ? 'bg-emerald-700 text-white' : 'bg-white border border-emerald-300 text-emerald-800'}"
          onclick={() => { view = 'green'; actionError = null; }}>Green</button>
      </div>

      <div class="grid gap-5 lg:grid-cols-[1fr_22rem]">
        {#if view === 'cost'}
          <CostPanel projectId={engineProjectId} {editorId} getSource={savedSource} {estimateId} />
        {:else if view === 'green'}
          {#key greenId}<GreenPanel projectId={engineProjectId} {editorId} {greenId} onPlanChanged={() => { void savedSource(); }} />{/key}
        {:else}
        <section class="bg-white rounded-xl border border-gray-200 p-4 space-y-3 min-w-0" aria-label="{tab} diagram">
          {#if diagram}
            <div class="flex flex-wrap items-center justify-between gap-2">
              <div class="flex gap-1" role="group" aria-label="Floor">
                {#each diagram.floors as f}
                  <button type="button" class="px-3 py-1 text-xs rounded-full border {floor === f.index ? 'bg-slate-800 text-white border-slate-800' : 'border-gray-300'}" onclick={() => floor = f.index}>{f.name}</button>
                {/each}
              </div>
              <span class="text-xs font-semibold px-2 py-1 rounded {current ? 'bg-emerald-100 text-emerald-800' : 'bg-amber-100 text-amber-900'}" data-testid="currency">
                {current ? 'Current — matches the saved plan' : 'Out of date — the plan changed since this diagram'}
              </span>
              <div class="flex items-center gap-1">
                <button type="button" class="px-2 py-1 text-sm border rounded" aria-label="Zoom out" onclick={() => zoom = Math.max(0.5, zoom - 0.25)}>−</button>
                <span class="text-xs w-10 text-center">{Math.round(zoom * 100)}%</span>
                <button type="button" class="px-2 py-1 text-sm border rounded" aria-label="Zoom in" onclick={() => zoom = Math.min(4, zoom + 0.25)}>+</button>
                <div class="ml-2 flex gap-1" role="group" aria-label="Export diagram">
                  <button type="button" class="px-3 py-1 text-sm border rounded hover:bg-gray-50" onclick={download}>SVG</button>
                  {#each ['pdf', 'dxf'] as const as fmt}
                    <button type="button" class="px-3 py-1 text-sm border rounded hover:bg-gray-50 disabled:opacity-50" disabled={exporting !== null}
                      title={fmt === 'pdf' ? 'A3 sheets at a stated scale, one per floor' : 'CAD drawing in millimetres with one layer per service'}
                      onclick={() => exportFile('diagram', fmt)}>{exporting === `diagram-${fmt}` ? 'Exporting…' : fmt.toUpperCase()}</button>
                  {/each}
                </div>
              </div>
            </div>
            <div class="overflow-auto border rounded-lg bg-white max-h-[75vh]" data-testid="diagram-view">
              <div class="diagram-fit" style="width: {zoom * 100}%">{@html svg}</div>
            </div>
          {:else}
            <p class="text-sm text-gray-600 p-6 text-center" data-testid="no-diagram">No {tab} diagram has been generated for this plan yet.</p>
          {/if}
        </section>
        {/if}

        <aside class="space-y-4">
          {#if view === 'diagrams'}
          <section class="bg-white rounded-xl border border-gray-200 p-4 space-y-3" aria-label="Generate">
            <h2 class="font-semibold text-gray-900">Generate from the saved plan</h2>
            {#if tab === 'electrical'}
              <label class="block"><span class="text-xs font-medium text-gray-700">Distribution board location</span>
                <select class="mt-1 w-full rounded-lg border border-gray-300 px-2 py-1.5 text-sm" bind:value={dbRoom} aria-label="Distribution board room">
                  <option value="">Automatic (near the entrance)</option>
                  {#each groundRooms as r}<option value={r.id}>{r.name}</option>{/each}
                </select></label>
              <label class="block"><span class="text-xs font-medium text-gray-700">Electrical wishes (optional)</span>
                <textarea class="mt-1 w-full rounded-lg border border-gray-300 px-2 py-1.5 text-sm min-h-16" maxlength="1000" bind:value={preferences}
                  aria-label="Electrical wishes" placeholder="e.g. AC in every bedroom, an EV charger in the parking"></textarea></label>
            {:else}
              <label class="block"><span class="text-xs font-medium text-gray-700">Water supply entry</span>
                <select class="mt-1 w-full rounded-lg border border-gray-300 px-2 py-1.5 text-sm" bind:value={entryRoom} aria-label="Water entry room">
                  <option value="">Automatic (road side)</option>
                  {#each groundRooms as r}<option value={r.id}>{r.name}</option>{/each}
                </select></label>
              <label class="block"><span class="text-xs font-medium text-gray-700">Drain exit (manhole)</span>
                <select class="mt-1 w-full rounded-lg border border-gray-300 px-2 py-1.5 text-sm" bind:value={exitRoom} aria-label="Drain exit room">
                  <option value="">Automatic (road side)</option>
                  {#each groundRooms as r}<option value={r.id}>{r.name}</option>{/each}
                </select></label>
              <p class="text-xs text-gray-500">Only rooms on the road side can hold the entry or exit; other choices fall back to automatic.</p>
            {/if}
            {#if actionError}<p role="alert" class="text-sm text-red-700 bg-red-50 rounded-lg px-3 py-2">{actionError}</p>{/if}
            <button type="button" class="w-full px-4 py-2.5 text-white rounded-lg font-semibold text-sm disabled:opacity-50 {tab === 'electrical' ? 'bg-amber-600 hover:bg-amber-700' : 'bg-blue-600 hover:bg-blue-700'}"
              disabled={busy} onclick={generate}>
              {busy ? 'Routing…' : `${diagram ? 'Regenerate' : 'Generate'} ${tab} diagram`}
            </button>
          </section>

          {/if}

          <section class="bg-white rounded-xl border border-gray-200 p-4 space-y-3" aria-label="Ask Greenprint">
            <div class="flex items-center justify-between">
              <h2 class="font-semibold text-gray-900">Ask Greenprint</h2>
              {#if chatLog.length}<button type="button" class="text-xs text-gray-500 hover:underline" onclick={() => { chatLog = []; chatContext = null; }}>New conversation</button>{/if}
            </div>
            {#if !chatLog.length}<p class="text-xs text-gray-500">The architect, the electrical and plumbing engineers, the cost estimator and the sustainability advisor. Try: “How green is it in Chennai?”, “Where are we?”, “Add an AC point in every bedroom”, “Plumb the house”, “What will it cost with premium finishes?”.</p>{/if}
            <ol class="space-y-2 max-h-96 overflow-y-auto" data-testid="agent-chat">
              {#each chatLog as line}
                <li class="text-sm rounded-lg px-3 py-2 whitespace-pre-line {line.role === 'user' ? 'bg-slate-800 text-white ml-6' : 'bg-gray-100 text-gray-900 mr-6'}" data-role={line.role}>
                  {line.text}
                  {#if line.revision}<a class="block mt-1 text-xs text-indigo-700 underline" href="/build/{engineProjectId}/layouts/{line.revision}">See the revised layout →</a>{/if}
                  {#if line.role === 'agent' && line.seconds !== undefined}
                    <span class="block text-[10px] text-gray-500 mt-1" data-testid="agent-meta">{helpers(line.tools)}</span>
                  {/if}
                </li>
              {/each}
              {#if asking}<li class="text-xs text-gray-500" role="status">Greenprint is working…</li>{/if}
            </ol>
            <form class="flex gap-2" onsubmit={(e) => { e.preventDefault(); ask(); }}>
              <input class="flex-1 rounded-lg border border-gray-300 px-2 py-1.5 text-sm" placeholder="Ask about this home…" aria-label="Message to Greenprint"
                bind:value={chatInput} maxlength="2000" disabled={asking} />
              <button type="submit" class="px-3 py-1.5 rounded-lg bg-blue-600 text-white text-sm font-semibold disabled:opacity-50" disabled={asking || !chatInput.trim()}>Ask</button>
            </form>
          </section>

          {#if diagram && view === 'diagrams'}
            <section class="bg-white rounded-xl border border-gray-200 p-4 space-y-3 text-sm" aria-label="Routing results" data-testid="routing-metrics">
              <div class="flex items-center justify-between"><h2 class="font-semibold text-gray-900">Routing results</h2>
                <span class="text-xs font-semibold px-2 py-0.5 rounded {diagram.status === 'complete' ? 'bg-emerald-100 text-emerald-800' : 'bg-red-100 text-red-800'}" data-testid="diagram-status">{diagram.status === 'complete' ? 'Complete' : 'Partial'}</span></div>
              {#each networks as [name, m] (name)}
                <div class="space-y-1" data-network={name}>
                  <h3 class="text-xs font-semibold text-gray-700 uppercase tracking-wide">{NETWORK_LABEL[name] ?? name}</h3>
                  <p class="text-xs" data-testid="connected-{name}">{m.endpoints_connected} of {m.endpoints_total} {name === 'wiring' ? 'supply points' : 'fixtures'} connected on allowed paths.</p>
                  <table class="w-full text-xs">
                    <thead><tr class="text-left text-gray-500"><th></th><th>Shortest path</th><th>Planned route</th></tr></thead>
                    <tbody>
                      <tr><td class="py-0.5">Route length</td><td>{km(m.baseline.length_mm)}</td><td>{km(m.selected.length_mm)}</td></tr>
                      <tr><td class="py-0.5">Bends</td><td>{m.baseline.bends}</td><td>{m.selected.bends}</td></tr>
                      <tr><td class="py-0.5">Floor transitions</td><td>{m.baseline.transitions}</td><td>{m.selected.transitions}</td></tr>
                    </tbody>
                  </table>
                  <p class="text-xs" data-testid="improvement-{name}">{m.improvement_pct && m.improvement_pct > 0 ? `${m.improvement_pct}% better than the shortest path, with fewer bends and floor changes.` : 'The shortest path is already the best route.'}</p>
                </div>
              {/each}
              <p class="text-xs text-gray-600">Lengths are along the routes, not material quantities.</p>
              {#if diagram.gravity === 'unverified'}
                <p class="text-xs text-amber-900 bg-amber-50 rounded px-2 py-1" data-testid="gravity">Drain directions are for planning; pipe slopes are set on site.</p>
              {/if}
              <ul class="text-xs space-y-1" aria-label="Circuits">
                {#each diagram.circuits as c}
                  {@const st = CIRCUIT_STYLE[c.id.replace(/\d+$/, '')]}
                  <li class="flex items-center gap-2"><span class="inline-block w-6 h-1 rounded" style="background: {st?.color ?? '#999'}"></span>{c.id} · {c.label}{c.floor !== null ? ` · floor ${c.floor}` : ''} · {c.endpoint_ids.length} points</li>
                {/each}
              </ul>
              {#if diagram.unresolved.length}<ul class="text-xs text-red-700 space-y-1" aria-label="Unresolved">{#each diagram.unresolved as u}<li>✕ {u.reason}</li>{/each}</ul>{/if}
              {#if diagram.preferences?.clarification}<p class="text-xs text-indigo-900 bg-indigo-50 rounded px-2 py-1">{diagram.preferences.clarification}</p>{/if}
              <details><summary class="text-xs cursor-pointer">Assumptions ({diagram.assumptions.length})</summary>
                <ul class="list-disc pl-4 text-xs text-gray-700 mt-1 space-y-0.5" data-testid="assumptions">{#each diagram.assumptions as a}<li>{a}</li>{/each}</ul></details>
            </section>
          {/if}


          {#if view === 'diagrams' && history[tab].length > 1}
            <section class="bg-white rounded-xl border border-gray-200 p-4 text-xs" aria-label="Diagram history">
              <h2 class="font-semibold text-gray-900 text-sm mb-2">History</h2>
              <ul class="space-y-1">
                {#each [...history[tab]].reverse() as h (h.id)}
                  <li><button type="button" class="hover:underline text-left {diagram?.id === h.id ? 'font-semibold' : ''}" onclick={() => show(h.id)}>
                    {new Date(h.created_at).toLocaleString()} · {h.source_hash === source.source_hash ? 'current plan' : 'older plan'} · {h.endpoints_connected}/{h.endpoints_total}
                  </button></li>
                {/each}
              </ul>
            </section>
          {/if}
        </aside>
      </div>
    {/if}
  </main>
</div>

